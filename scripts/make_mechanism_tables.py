"""Emit the mechanism and benchmarking-power LaTeX tables.

Companion to `scripts/make_latex_tables.py`, honouring the same rule from
project_plan.md §8: no number in the paper exists anywhere except as a
query against a results file, never hand-typed.

Writes to `paper/tables/*.tex`:
  tab_rho_local.tex        -- global vs boundary-local Tier-A redundancy
                              against the realised aggregation gain
  tab_resolvability.tex    -- which reported wins survive a seed-averaged
                              per-instance bootstrap
  tab_power.tex            -- test errors needed to resolve a given
                              relative AURC effect
  tab_redundancy_screen.tex -- the 16-candidate screen, showing why the
                              between-dataset decoupling experiment is
                              structurally unavailable
  tab_capacity_sweep.tex   -- the within-dataset (fixed-K) decoupling
                              experiment

Inputs are the CSVs written by `make_mechanism_figures.py`,
`analyze_selection_bias.py`, `screen_redundancy_candidates.py` and
`run_capacity_sweep.py`. Each table is skipped with a message if its
input is missing, so this is safe to run mid-sweep.

Usage:
    python scripts/make_mechanism_tables.py --tiers AC
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

TABLE_DIR = ROOT / "paper" / "tables"
CAPACITY_PATH = ROOT / "results" / "capacity_sweep.parquet"

DATASET_META = {
    "adult": ("Adult", 2),
    "german_credit": ("German Credit", 2),
    "electricity": ("Electricity$^{\\dagger}$", 2),
    "satimage": ("Satimage", 6),
    "wine_quality_white": ("Wine Quality", 7),
    "letter": ("Letter", 26),
}


def _esc(s: str) -> str:
    return str(s).replace("_", "\\_")


def _name(ds: str) -> str:
    return DATASET_META.get(ds, (_esc(ds), 0))[0]


def _k(ds: str) -> str:
    return str(DATASET_META.get(ds, ("", 0))[1] or "?")


def _order(datasets) -> list[str]:
    """Binary first, then by class count -- the axis the confound runs
    along, so the reader can see it without re-sorting."""
    return sorted(datasets, key=lambda d: (DATASET_META.get(d, ("", 99))[1], d))


def _write(name: str, lines: list[str]) -> None:
    (TABLE_DIR / f"{name}.tex").write_text("\n".join(lines) + "\n")
    print(f"wrote {(TABLE_DIR / (name + '.tex')).relative_to(ROOT)}")


def table_rho_local(tiers: str) -> None:
    src = TABLE_DIR / f"mechanism_per_dataset_{tiers}.csv"
    if not src.exists():
        print(f"[skip] tab_rho_local: run make_mechanism_figures.py --tiers {tiers}")
        return
    d = pd.read_csv(src)
    lines = [
        "% GENERATED by scripts/make_mechanism_tables.py -- do not edit by hand.",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Boundary-local versus global Tier-A rank redundancy, and "
        "the realised AURC gain of the pre-registered aggregator "
        "(\\texttt{A1\\_logreg}) over the best single signal. "
        "$\\rho_{\\mathrm{local}}$ is the minimum $|\\rho_{\\mathrm{Spearman}}|$ "
        "against MSP over the Tier-A bank, restricted to the top $10\\%$ of "
        "points by MSP risk; $\\rho_{\\mathrm{global}}$ is the same statistic "
        "over the whole test set. Negative $\\Delta$ favours aggregation. "
        "The two statistics disagree by up to $0.56$ on exactly the datasets "
        "where aggregation helps.}",
        "\\label{tab:rho_local}",
        "\\begin{tabular}{l r r r r}", "\\toprule",
        "Dataset & $K$ & $\\rho_{\\mathrm{global}}$ & "
        "$\\rho_{\\mathrm{local}}$ & $\\Delta$AURC (\\%) \\\\", "\\midrule",
    ]
    for ds in _order(d.dataset):
        r = d[d.dataset == ds].iloc[0]
        lines.append(
            f"{_name(ds)} & {_k(ds)} & {r.rho_global:.4f} & "
            f"{r.rho_local:.4f} & {r.gain_pct:+.2f} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    _write("tab_rho_local", lines)


def table_resolvability(tiers: str) -> None:
    src = TABLE_DIR / f"selection_bias_null_{tiers}.csv"
    if not src.exists():
        print(f"[skip] tab_resolvability: run analyze_selection_bias.py --tiers {tiers}")
        return
    d = pd.read_csv(src)
    lines = [
        "% GENERATED by scripts/make_mechanism_tables.py -- do not edit by hand.",
        "\\begin{table*}[t]", "\\centering",
        "\\caption{Which reported aggregation wins are statistically "
        "resolvable. Margins are relative AURC differences against the best "
        "single signal (negative favours aggregation). "
        "\\emph{within-run SD} is the paired per-instance bootstrap spread "
        "inside a single run; \\emph{10-seed CI} is the $95\\%$ interval for "
        "the 10-seed mean, obtained by averaging each bootstrap iteration "
        "across seeds. A claim is resolvable only if its 10-seed interval "
        "excludes zero. Rows are ordered by test \\emph{error} count, which "
        "is what governs the precision -- not by row count.}",
        "\\label{tab:resolvability}",
        "\\begin{tabular}{l r r r r r c}", "\\toprule",
        "Dataset & errors & best-of-$N$ & within-run SD & 10-seed CI & "
        "pre-reg. & resolvable? \\\\", "\\midrule",
    ]
    for _, r in d.sort_values("n_errors").iterrows():
        mark = "\\checkmark" if bool(r.best_resolvable) else "--"
        lines.append(
            f"{_name(r.dataset)} & {r.n_errors:.0f} & {r.best_margin_pct:+.2f} & "
            f"{r.within_seed_sd_pct:.2f} & "
            f"[{r.seed_avg_ci_lo_pct:+.2f}, {r.seed_avg_ci_hi_pct:+.2f}] & "
            f"{r.prereg_margin_pct:+.2f} & {mark} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    _write("tab_resolvability", lines)


def table_power(tiers: str) -> None:
    src = TABLE_DIR / f"aurc_power_{tiers}.csv"
    if not src.exists():
        print(f"[skip] tab_power: run analyze_selection_bias.py --tiers {tiers}")
        return
    d = pd.read_csv(src)
    seed_cols = [c for c in d.columns if c.startswith("errors_at_")]
    counts = [c.split("_")[2] for c in seed_cols]
    k = float(d.scaling_k.iloc[0])
    lines = [
        "% GENERATED by scripts/make_mechanism_tables.py -- do not edit by hand.",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Test \\emph{errors} required to resolve a relative AURC "
        "difference at $80\\%$ power (two-sided, $\\alpha{=}0.05$), from the "
        f"measured relative standard error $k/\\sqrt{{n_{{\\mathrm{{err}}}}}}$ "
        f"with $k={k:.2f}$ (pooled over six datasets spanning 34--2533 "
        "errors). Averaging over independent runs shrinks the requirement "
        "linearly in the number of seeds. No dataset in the registry reaches "
        "the single-run requirement for a $5\\%$ effect.}",
        "\\label{tab:power}",
        "\\begin{tabular}{l " + "r" * len(seed_cols) + "}", "\\toprule",
        "Relative effect & " + " & ".join(f"{c} seed{'s' if c != '1' else ''}"
                                          for c in counts) + " \\\\",
        "\\midrule",
    ]
    for _, r in d.iterrows():
        cells = [f"{int(r[c]):,}".replace(",", "\\,") for c in seed_cols]
        lines.append(f"{100 * r.relative_effect:.0f}\\% & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    _write("tab_power", lines)


def table_screen(q: float = 0.10) -> None:
    src = TABLE_DIR / f"redundancy_screen_q{q}.csv"
    if not src.exists():
        print("[skip] tab_redundancy_screen: run screen_redundancy_candidates.py")
        return
    d = pd.read_csv(src).sort_values("rho_local", ascending=False)
    usable = d[d.test_errors >= 50]
    redundant = d[d.rho_local >= 0.6]
    lines = [
        "% GENERATED by scripts/make_mechanism_tables.py -- do not edit by hand.",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Screen of 16 multiclass OpenML candidates for a "
        "\\emph{locally redundant} $K \\ge 3$ dataset, which would decouple "
        "$\\rho_{\\mathrm{local}}$ from class count. None exists: the "
        "candidates with enough test errors to resolve anything reach only "
        f"$\\rho_{{\\mathrm{{local}}}} = {usable.rho_local.max():.3f}$, and those "
        f"that are locally redundant have at most {int(redundant.test_errors.max())} "
        "test errors. Local redundancy tracks base \\emph{accuracy} "
        "(Spearman $0.50$), and an accurate model produces too few errors "
        "for a risk--coverage curve to resolve. The two requirements are in "
        "structural tension, so the decoupling test must instead hold the "
        "dataset fixed (Table~\\ref{tab:capacity}).}",
        "\\label{tab:screen}",
        "\\begin{tabular}{l r r r r}", "\\toprule",
        "Candidate & $K$ & base acc. & test errors & "
        "$\\rho_{\\mathrm{local}}$ \\\\", "\\midrule",
    ]
    for _, r in d.iterrows():
        lines.append(
            f"{_esc(r['name'])} & {int(r.K)} & {r.base_acc:.3f} & "
            f"{int(r.test_errors)} & {r.rho_local:.3f} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    _write("tab_redundancy_screen", lines)


def table_capacity() -> None:
    if not CAPACITY_PATH.exists():
        print("[skip] tab_capacity: run run_capacity_sweep.py")
        return
    from scipy.stats import spearmanr

    d = pd.read_parquet(CAPACITY_PATH)
    lines = [
        "% GENERATED by scripts/make_mechanism_tables.py -- do not edit by hand.",
        "\\begin{table*}[t]", "\\centering",
        "\\caption{Decoupling $\\rho_{\\mathrm{local}}$ from class count by "
        "sweeping base-model capacity at \\emph{fixed} $K$. Weakening the "
        "base model moves $\\rho_{\\mathrm{local}}$ without changing the "
        "dataset, the class count, the signal bank or the aggregator. "
        "$\\Delta$AURC is the pre-registered aggregator against the best "
        "single signal (negative favours aggregation). Binary datasets are "
        "the control: the degeneracy theorem pins "
        "$\\rho_{\\mathrm{local}} = 1$ at every capacity, so there is no "
        "dose to respond to.}",
        "\\label{tab:capacity}",
        "\\begin{tabular}{l r l r r r r r}", "\\toprule",
        "Dataset & $K$ & capacity & base acc. & errors & "
        "$\\rho_{\\mathrm{local}}$ & $\\Delta$AURC (\\%) & $n$ \\\\",
        "\\midrule",
    ]
    order = [c for c in ["tiny", "very_weak", "weak", "medium", "strong", "full"]
             if c in set(d.capacity)]
    for ds in _order(d.dataset.unique()):
        g = d[d.dataset == ds]
        for cap in order:
            gc = g[g.capacity == cap]
            if gc.empty:
                continue
            lines.append(
                f"{_name(ds)} & {int(gc.K.iloc[0])} & {_esc(cap)} & "
                f"{gc.base_acc.mean():.3f} & {gc.test_errors.mean():.0f} & "
                f"{gc.rho_local_test.mean():.4f} & "
                f"{gc.gain_vs_best_single_pct.mean():+.2f} & {len(gc)} \\\\"
            )
        # The dose-response statistic, per dataset, right under its rows.
        if int(g.K.iloc[0]) >= 3 and g.rho_local_test.nunique() > 2:
            res = spearmanr(g.rho_local_test, g.gain_vs_best_single_pct)
            lines.append(
                "\\multicolumn{8}{l}{\\quad\\emph{"
                f"Spearman$(\\rho_{{\\mathrm{{local}}}}, \\Delta) = "
                f"{res.statistic:+.3f}$, $p={res.pvalue:.3f}$, "
                f"$n={len(g)}$ runs}}}} \\\\"
            )
        lines.append("\\midrule")
    if lines[-1] == "\\midrule":
        lines.pop()
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    _write("tab_capacity_sweep", lines)


def table_shift(kind: str = "gaussian_noise", dataset: str = "satimage") -> None:
    """RQ2 under controlled shift, with the signal-takeover column that
    explains the reversal."""
    src = TABLE_DIR / f"shift_gaps_{kind}.csv"
    shift_parquet = ROOT / "results" / "shift_results.parquet"
    if not src.exists() or not shift_parquet.exists():
        print("[skip] tab_shift: run analyze_shift_results.py")
        return
    d = pd.read_csv(src)
    d = d[d.dataset == dataset].sort_values("intensity")
    if d.empty:
        print(f"[skip] tab_shift: no rows for {dataset}")
        return

    # Best single signal's identity per intensity, which is the column that
    # turns the reversal from a number into an explanation.
    raw = pd.read_parquet(shift_parquet)
    raw = raw[(raw.dataset == dataset) & (raw.shift_kind == kind)
              & (~raw.method.str.endswith("__conformal"))]
    piv = raw.groupby(["intensity", "method"])["aurc"].mean().unstack()
    sigs = [c for c in piv.columns if c.startswith("signal_")]
    best_name = piv[sigs].idxmin(axis=1).str.replace("signal_", "", regex=False)

    # Caption built as ONE f-string. Concatenating an f-string with plain
    # literals leaves `}}` unescaped in the plain parts, which emitted a
    # stray closing brace into the LaTeX and broke the caption.
    caption = (
        f"\\caption{{RQ2 under controlled Gaussian covariate shift on "
        f"{_name(dataset)} ($\\rho_{{\\mathrm{{local}}}} \\approx 0.34$, so a "
        f"dataset on which aggregation \\emph{{can}} help). Everything is fit "
        f"once on the clean splits. The \\emph{{relative}} gap is the test: "
        f"the absolute gap grows monotonically only because MSP's own AURC "
        f"rises by $36\\times$ over this range. As shift increases, Tier-C "
        f"geometry overtakes MSP as the best single signal, and the learned "
        f"stack --- whose weights were fit where geometry was uninformative "
        f"--- falls behind both the best single signal and the "
        f"parameter-free rank average.}}"
    )
    a0 = piv.get("A0_rank", pd.Series(dtype=float))
    a1 = piv.get("A1_logreg", pd.Series(dtype=float))
    lines = [
        "% GENERATED by scripts/make_mechanism_tables.py -- do not edit by hand.",
        "\\begin{table*}[t]", "\\centering", caption,
        "\\label{tab:shift}",
        "\\begin{tabular}{r r r l r r r r r}", "\\toprule",
        " & & & & \\multicolumn{4}{c}{AURC} & \\\\",
        "\\cmidrule(lr){5-8}",
        "Intensity & base err. & $\\rho_{\\mathrm{local}}$ & best single signal & "
        "best single & MSP & \\texttt{A0\\_rank} & \\texttt{A1\\_logreg} & "
        "rel. gap (\\%) \\\\", "\\midrule",
    ]
    for _, r in d.iterrows():
        i = r.intensity
        lines.append(
            f"{i:.2f} & {r.base_error:.3f} & {r.rho_local:.3f} & "
            f"{_esc(best_name.get(i, '?'))} & {r.best_single_aurc:.4f} & "
            f"{r.msp_aurc:.4f} & {a0.get(i, float('nan')):.4f} & "
            f"{a1.get(i, float('nan')):.4f} & {r.rel_gap_best_pct:+.1f} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    _write("tab_shift", lines)


def table_shift_conformal(kind: str = "gaussian_noise", dataset: str = "satimage") -> None:
    src = TABLE_DIR / f"shift_conformal_{kind}.csv"
    if not src.exists():
        print("[skip] tab_shift_conformal: run analyze_shift_results.py")
        return
    d = pd.read_csv(src)
    d = d[d.dataset == dataset]
    if d.empty:
        print(f"[skip] tab_shift_conformal: no rows for {dataset}")
        return
    viol = d.pivot_table(index="conformal_alpha", columns="intensity",
                         values="violation_rate")
    cov = d.pivot_table(index="conformal_alpha", columns="intensity",
                        values="mean_coverage")
    intensities = list(viol.columns)
    lines = [
        "% GENERATED by scripts/make_mechanism_tables.py -- do not edit by hand.",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Empirical violation rate $P(\\mathrm{risk} > \\alpha)$ of the "
        "conformal guarantee when $\\hat\\tau$ is calibrated on clean data and "
        "applied under shift, against the nominal $\\delta = 0.1$. Attained "
        "coverage is given in parentheses: the bound fails while the system "
        "is still answering most inputs, so it does not announce its own "
        "failure. $\\alpha = 0.01$ abstains on everything, making its zero "
        "violation rate vacuous rather than a success.}",
        "\\label{tab:shift_conformal}",
        "\\begin{tabular}{l " + "r" * len(intensities) + "}", "\\toprule",
        "$\\alpha$ & " + " & ".join(f"{i:g}" for i in intensities) + " \\\\",
        "\\cmidrule(lr){2-" + str(1 + len(intensities)) + "}",
        " & \\multicolumn{" + str(len(intensities)) +
        "}{c}{shift intensity} \\\\", "\\midrule",
    ]
    for alpha in viol.index:
        cells = [f"{viol.loc[alpha, i]:.2f} ({cov.loc[alpha, i]:.2f})"
                 for i in intensities]
        lines.append(f"{alpha:g} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    _write("tab_shift_conformal", lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tiers", default="AC")
    ap.add_argument("--screen-q", type=float, default=0.10)
    ap.add_argument("--shift-dataset", default="satimage")
    args = ap.parse_args()
    TABLE_DIR.mkdir(parents=True, exist_ok=True)

    table_rho_local(args.tiers)
    table_resolvability(args.tiers)
    table_power(args.tiers)
    table_screen(args.screen_q)
    table_capacity()
    table_shift(dataset=args.shift_dataset)
    table_shift_conformal(dataset=args.shift_dataset)


if __name__ == "__main__":
    main()
